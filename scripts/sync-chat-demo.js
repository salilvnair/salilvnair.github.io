#!/usr/bin/env node
/**
 * Builds convengine-chat-demo as a static export and syncs it into
 * public/framework/convengine-chat/, then injects the client-side API mock script tag.
 *
 * Run from the salilvnair.github.io root:
 *   npm run sync-chat-demo
 */

import { execSync } from 'child_process';
import { readFileSync, writeFileSync, cpSync, existsSync, unlinkSync, renameSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname   = dirname(fileURLToPath(import.meta.url));
const ROOT        = resolve(__dirname, '..');
const CHAT_DEMO   = '/Users/salilvnair/workspace/git/salilvnair/convengine-chat-demo';
const DEST        = resolve(ROOT, 'public/framework/convengine-chat');
const ROOT_NEXT_CONFIG = resolve(CHAT_DEMO, 'next.config.mjs');
const LOCAL_ONLY_NEXT_CONFIG = resolve(CHAT_DEMO, 'local_only/next.config.mjs');
const hadOriginalRootConfig = existsSync(ROOT_NEXT_CONFIG);

// The demo's app/api/* routes (message + SSE stream) are dev-only mock
// handlers for `npm run dev` — the static export instead uses the
// client-side api-mock.js fetch interceptor bundled below. Route Handlers
// (especially the dynamic stream/[conversationId] one) aren't compatible
// with `output: 'export'`, so they're moved out of the app/ tree for the
// duration of the build and restored afterward, same pattern as the
// next.config.mjs swap.
const API_DIR        = resolve(CHAT_DEMO, 'app/api');
const API_DIR_BACKUP = resolve(CHAT_DEMO, '.sync-chat-demo-api-backup');
// Recover from a previous crashed run that moved app/api aside but never restored it.
if (!existsSync(API_DIR) && existsSync(API_DIR_BACKUP)) {
  renameSync(API_DIR_BACKUP, API_DIR);
}
const hadApiDir = existsSync(API_DIR);

// The static site's stand-in for app/api: scripts/chat-demo-api-mock.entry.js
// bundles the demo's own fake-chat / fake-audit / audit-store modules into one
// browser script, so the published demo answers and audits like `npm run dev`.
// Must run while app/api is still in place — audit-store.js lives there.
async function bundleApiMock() {
  const { build } = await import('esbuild'); // ships with vite
  const result = await build({
    entryPoints: [resolve(__dirname, 'chat-demo-api-mock.entry.js')],
    bundle:      true,
    format:      'iife',
    platform:    'browser',
    target:      'es2019',
    minify:      true,
    write:       false,
    alias:       { '@chat-demo': CHAT_DEMO },
    banner:      { js: '// Auto-generated by scripts/sync-chat-demo.js from scripts/chat-demo-api-mock.entry.js' },
    logLevel:    'warning',
  });
  return result.outputFiles[0].text;
}

// ── 1. Prepare root next.config.mjs from local_only template + overrides ─────
console.log('📝  Preparing root next.config.mjs for static export...');
const originalRootConfig = hadOriginalRootConfig ? readFileSync(ROOT_NEXT_CONFIG, 'utf8') : null;
const sourceConfig = existsSync(LOCAL_ONLY_NEXT_CONFIG)
  ? readFileSync(LOCAL_ONLY_NEXT_CONFIG, 'utf8')
  : `/** @type {import('next').NextConfig} */
const nextConfig = {
  transpilePackages: ['@salilvnair/convengine-chat'],
};

export default nextConfig;
`;

const normalizedSource = sourceConfig.replace(/export\s+default\s+nextConfig\s*;?\s*$/m, '').trimEnd();
const patchedConfig = `${normalizedSource}

const __syncChatDemoExportConfig = {
  output: 'export',
  basePath: '/framework/convengine-chat',
  // Lets the app prefix URLs next/link can't: window.open, widget config URLs.
  env: { ...(nextConfig.env || {}), NEXT_PUBLIC_BASE_PATH: '/framework/convengine-chat' },
  trailingSlash: false,
};

export default { ...nextConfig, ...__syncChatDemoExportConfig };
`;
writeFileSync(ROOT_NEXT_CONFIG, patchedConfig, 'utf8');

// ── 1a. Bundle the client-side API mock (needs app/api in place) ─────────
console.log('🧩  Bundling api-mock.js from the demo mock modules...');
const apiMockSource = await bundleApiMock();

// ── 1b. Move app/api aside — dev-only mock routes, incompatible with
//        `output: 'export'` (the dynamic stream/[conversationId] route has
//        no generateStaticParams, and neither route is needed once the
//        static build's client-side api-mock.js takes over). ───────────────
if (hadApiDir) {
  console.log('📦  Moving app/api aside (dev-only mock routes, not exportable)...');
  renameSync(API_DIR, API_DIR_BACKUP);
}

try {
  // ── 2. Build ───────────────────────────────────────────────────────────────
  console.log('🔨  Building convengine-chat-demo (npm run build)...');
  execSync('npm run build', { cwd: CHAT_DEMO, stdio: 'inherit' });

  const OUT = resolve(CHAT_DEMO, 'out');
  if (!existsSync(OUT)) {
    throw new Error('Build output directory "out/" not found in ' + CHAT_DEMO);
  }

  // ── 3. Copy output → public/framework/convengine-chat ────────────────────
  console.log('📂  Copying out/ → public/framework/convengine-chat/...');
  cpSync(OUT, DEST, { recursive: true });

  // ── 4. Write the bundled api-mock.js ──────────────────────────────────────
  writeFileSync(resolve(DEST, 'api-mock.js'), apiMockSource, 'utf8');

  // ── 5. Inject api-mock.js script tag ──────────────────────────────────────
  console.log('💉  Injecting api-mock.js script tag into HTML files...');
  const MOCK_TAG   = '<script src="/framework/convengine-chat/api-mock.js"></script>';
  const FIRST_CHUNK = '<script src="/framework/convengine-chat/_next/static/chunks/fd9d1056-';

  for (const file of ['index.html', 'fullscreen.html', 'audit.html']) {
    const filePath = resolve(DEST, file);
    if (!existsSync(filePath)) {
      console.warn(`  ⚠️  ${file} not found, skipping`);
      continue;
    }
    let html = readFileSync(filePath, 'utf8');
    if (html.includes(MOCK_TAG)) {
      console.log(`  ✅  ${file} already has the mock tag`);
    } else {
      // Inject synchronously before the first async Next.js chunk
      const idx = html.indexOf(FIRST_CHUNK);
      if (idx === -1) {
        // Fallback: inject right after <head>
        html = html.replace('<head>', '<head>' + MOCK_TAG);
      } else {
        html = html.slice(0, idx) + MOCK_TAG + html.slice(idx);
      }
      writeFileSync(filePath, html, 'utf8');
      console.log(`  ✅  Injected into ${file}`);
    }
  }

  console.log('\n✨  Done! Chat demo synced to public/framework/convengine-chat/');

} finally {
  // ── 6. Restore root next.config.mjs ───────────────────────────────────────
  console.log('♻️   Restoring root next.config.mjs...');
  if (hadOriginalRootConfig) {
    writeFileSync(ROOT_NEXT_CONFIG, originalRootConfig, 'utf8');
  } else if (existsSync(ROOT_NEXT_CONFIG)) {
    unlinkSync(ROOT_NEXT_CONFIG);
  }

  // ── 7. Restore app/api ─────────────────────────────────────────────────────
  if (hadApiDir && existsSync(API_DIR_BACKUP)) {
    console.log('♻️   Restoring app/api...');
    renameSync(API_DIR_BACKUP, API_DIR);
  }
}
